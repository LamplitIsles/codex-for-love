export const english: CompanionTranslate = (key, params) =>
  companionEn[key].replace(/\{(\w+)\}/gu, (match, name: string) => {
    const value = params?.[name];
    return typeof value === "string" || typeof value === "number"
      ? String(value)
      : match;
  });
